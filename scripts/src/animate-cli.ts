import { readFileSync, writeFileSync } from 'fs';
import { prepareAnimation, compactChecks } from '<upstream checkout>/packages/core/src/animation/animation-tool.ts';
import { renderContactSheet } from '<upstream checkout>/packages/core/src/animation/contact-sheet.ts';
import { rigFor } from '<upstream checkout>/packages/core/src/animation/rigs.ts';
import { rigFromModel } from '<upstream checkout>/packages/core/src/animation/model-rig.ts';

function usage(): never {
  console.error(`usage: node animate.mjs <animation.json> [--out <file.lua>] [--sheet <file.png>] [--locomotion] [--grounded] [--waive id,id] [--parent <path>] [--rig-json <reading.json>]
Compiles a pose-format animation (see references/character-animation.md) for the stock R15 or R6 rig,
runs the motion checks, optionally renders a contact sheet PNG, and writes Luau that builds the
KeyframeSequence in Studio and registers a temporary preview id. Run that Luau with execute_luau.`);
  process.exit(2);
}
const args = process.argv.slice(2);
if (args.length === 0 || args[0].startsWith('-')) usage();
const input = args[0];
const opt = (name: string) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : undefined; };
const flag = (name: string) => args.includes(name);
let animation: unknown;
try { animation = JSON.parse(readFileSync(input, 'utf8')); } catch (e) { console.error(`Could not read ${input} as JSON: ${(e as Error).message}`); process.exit(1); }
let model: any = undefined;
const rigJson = opt('--rig-json');
if (rigJson) {
  let reading: any;
  try { reading = JSON.parse(readFileSync(rigJson, 'utf8')); } catch (e) { console.error(`Could not read ${rigJson}: ${(e as Error).message}`); process.exit(1); }
  const r = rigFromModel(reading);
  if (!r.ok) { console.log(JSON.stringify({ ok: false, errors: r.errors }, null, 2)); process.exit(1); }
  model = r.rig;
  if (r.notes.length) console.error('rig notes:\n- ' + r.notes.join('\n- '));
  if (animation && typeof animation === 'object' && (animation as any).rig !== reading.path) {
    console.error(`note: animation.rig set to the rig reading's path ${reading.path}`);
    (animation as any).rig = reading.path;
  }
}
const result = prepareAnimation(animation, {
  locomotion: flag('--locomotion'), grounded: flag('--grounded'),
  waive: opt('--waive') ? opt('--waive')!.split(',') : undefined,
}, model);
if (!result.ok) { console.log(JSON.stringify({ ok: false, errors: result.errors }, null, 2)); process.exit(1); }
const { sequence, report, failing, waived } = result.value;
const rig = model ?? rigFor(sequence.rig);
const summary: Record<string, unknown> = {
  ok: failing.length === 0, name: sequence.name, rig: sequence.rig, loop: sequence.loop, priority: sequence.priority,
  duration: sequence.duration, keyframes: sequence.keyframes.length, poses: sequence.keyedPoseCount,
  markers: sequence.markerCount, inBetweens: sequence.inBetweenCount, failing, waived, checks: compactChecks(report),
};
const sheetPath = opt('--sheet');
if (sheetPath) {
  const sheet = renderContactSheet(sequence, undefined, { locomotion: flag('--locomotion'), rig });
  writeFileSync(sheetPath, sheet.png);
  summary.sheet = { path: sheetPath, times: sheet.times, labels: sheet.labels };
}
const outPath = opt('--out');
if (outPath) {
  const parent = opt('--parent') ?? 'game.ServerStorage';
  writeFileSync(outPath, toLuau(sequence, parent));
  summary.luau = outPath;
}
console.log(JSON.stringify(summary, null, 2));
process.exit(failing.length === 0 ? 0 : 3);

function luaString(s: string) { return JSON.stringify(s); }
function num(n: number) { return Number.isFinite(n) ? String(Math.round(n * 1e6) / 1e6) : '0'; }
function toLuau(seq: any, parent: string): string {
  const L: string[] = [];
  L.push('-- Generated by roblox-vfx-animation/scripts/animate.mjs. Run with execute_luau.');
  L.push('local function P(name, w, c, es, ed, kids)');
  L.push('\tlocal p = Instance.new("Pose")');
  L.push('\tp.Name = name; p.Weight = w');
  L.push('\tp.CFrame = CFrame.new(c[1],c[2],c[3],c[4],c[5],c[6],c[7],c[8],c[9],c[10],c[11],c[12])');
  L.push('\tp.EasingStyle = Enum.PoseEasingStyle[es]; p.EasingDirection = Enum.PoseEasingDirection[ed]');
  L.push('\tfor _, k in kids do k.Parent = p end');
  L.push('\treturn p');
  L.push('end');
  L.push('local seq = Instance.new("KeyframeSequence")');
  L.push(`seq.Name = ${luaString(seq.name)}`);
  L.push(`seq.Loop = ${seq.loop ? 'true' : 'false'}`);
  L.push(`seq.Priority = Enum.AnimationPriority.${seq.priority}`);
  const pose = (p: any): string =>
    `P(${luaString(p.part)},${p.weight},{${p.cframe.map(num).join(',')}},${luaString(p.easingStyle)},${luaString(p.easingDirection)},{${p.children.map(pose).join(',')}})`;
  for (const k of seq.keyframes) {
    L.push('do');
    L.push('\tlocal k = Instance.new("Keyframe")');
    L.push(`\tk.Time = ${num(k.time)}`);
    if (k.name) L.push(`\tk.Name = ${luaString(k.name)}`);
    L.push(`\t${pose(k.root)}.Parent = k`);
    for (const m of k.markers ?? []) {
      L.push(`\tdo local m = Instance.new("KeyframeMarker"); m.Name = ${luaString(m.name)}; m.Value = ${luaString(m.value)}; m.Parent = k end`);
    }
    L.push('\tk.Parent = seq');
    L.push('end');
  }
  L.push(`local folder = ${parent}:FindFirstChild("Animations") or Instance.new("Folder")`);
  L.push(`folder.Name = "Animations"; folder.Parent = ${parent}`);
  L.push('local old = folder:FindFirstChild(seq.Name)');
  L.push('if old then old:Destroy() end');
  L.push('seq.Parent = folder');
  L.push('local ok, id = pcall(function() return game:GetService("AnimationClipProvider"):RegisterAnimationClip(seq) end)');
  L.push('local previewId = ok and tostring(id) or nil');
  L.push('seq:SetAttribute("PreviewId", previewId)');
  L.push('return string.format("built %s (%d keyframes); preview id: %s", seq:GetFullName(), #seq:GetKeyframes(), tostring(previewId))');
  return L.join('\n') + '\n';
}
